"""
Visualize the *IK warm-start* Go2 trajectory with Meshcat.

Assumptions:
- Run this script from the `UnitreeGo2/urdf` directory.
- This file lives in the same directory as `go2_description.urdf`.
- The IK trajectory (.npz) was generated by `generate_go2_smr.py` in the
  project root (`/mnt/e/3ddogs`) and saved as `<sequence>_go2_ik.npz`.

Example:

    cd /mnt/e/3ddogs/UnitreeGo2/urdf
    python visualize_go2_ik.py --ik ../../optical_sync_align_d29_t1_a_ready_go2_ik.npz
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import numpy as np
import pinocchio as pin
from pinocchio.visualize import MeshcatVisualizer

# Make project root importable so we can import `retargeting`.
THIS_FILE = Path(__file__).resolve()
PROJECT_ROOT = THIS_FILE.parents[2]  # /mnt/e/3ddogs
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from retargeting import Go2Kinematics, mocap_to_robot_positions  # type: ignore  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser(description="Visualize Go2 IK trajectory with Meshcat")
    parser.add_argument(
        "--ik",
        type=str,
        required=True,
        help="Path to <sequence>_go2_ik.npz (relative to this directory).",
    )
    parser.add_argument(
        "--uvm",
        type=str,
        default="",
        help="Optional path to <sequence>_go2_uvm.npz (relative to this directory) for target keypoints.",
    )
    parser.add_argument(
        "--frame",
        type=int,
        default=-1,
        help="If >=0, only visualize this frame (static); otherwise animate all frames.",
    )
    args = parser.parse_args()

    ik_path = (THIS_FILE.parent / args.ik).resolve()
    if not ik_path.is_file():
        raise FileNotFoundError(ik_path)

    data = np.load(ik_path)
    q = data["q"]
    dt = float(data.get("dt", 1.0 / 60.0))
    T = q.shape[0]

    # Optional UVM keypoints for target visualization (all frames).
    targets_robot = None
    if args.uvm:
        uvm_path = (THIS_FILE.parent / args.uvm).resolve()
        uv_data = np.load(uvm_path, allow_pickle=True)
        positions = uv_data["positions"]  # (T, N, 3) in mocap world
        targets_robot = mocap_to_robot_positions(positions)  # (T, N, 3) in robot world

    # Build kinematic model from the local URDF.
    urdf_path = THIS_FILE.parent / "go2_description.urdf"
    go2 = Go2Kinematics.from_urdf(urdf_path)
    model = go2.model

    # Build visual geometry model with explicit package_dirs for relative meshes.
    geom_model = pin.buildGeomFromUrdf(
        model,
        str(urdf_path),
        pin.GeometryType.VISUAL,
        None,
        [str(urdf_path.parent)],
    )

    viz = MeshcatVisualizer(model, None, geom_model)
    viz.initViewer(open=True)
    viz.loadViewerModel(rootNodeName="go2")

    viewer = viz.viewer

    # Optional per-frame target spheres (red).
    if targets_robot is not None:
        import meshcat.geometry as mg
        import meshcat.transformations as mt

        T_targets, N, _ = targets_robot.shape
        sphere_geom = mg.Sphere(0.02)
        sphere_mat = mg.MeshLambertMaterial(color=0xFF0000)  # red targets
        for j in range(N):
            viewer[f"targets/joint_{j}"].set_object(sphere_geom, sphere_mat)

        def update_targets(t: int) -> None:
            pts = targets_robot[min(t, T_targets - 1)]
            for j, p in enumerate(pts):
                Tf = mt.translation_matrix(p)
                viewer[f"targets/joint_{j}"].set_transform(Tf)
    else:
        def update_targets(t: int) -> None:
            return

    # Initial display.
    frame_idx = args.frame if args.frame >= 0 else 0
    frame_idx = max(0, min(frame_idx, T - 1))
    viz.display(q[frame_idx])
    update_targets(frame_idx)
    print(f"Loaded IK: {ik_path}")
    print(f"Meshcat URL: {viz.viewer.url()}")

    # If a specific frame is requested, stay on that frame.
    if args.frame >= 0:
        try:
            while True:
                time.sleep(1.0)
        except KeyboardInterrupt:
            return

    # Otherwise, playback loop over all frames.
    try:
        while True:
            for t in range(T):
                viz.display(q[t])
                update_targets(t)
                time.sleep(dt)
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()


