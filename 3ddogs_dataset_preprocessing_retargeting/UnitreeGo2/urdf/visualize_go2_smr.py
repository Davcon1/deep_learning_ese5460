"""
Simple Go2 SMR visualizer using Meshcat.

Assumptions:
- Run this script from the `UnitreeGo2/urdf` directory.
- This file lives in the same directory as `go2_description.urdf`.
- The SMR trajectory (.npz) was generated by `generate_go2_smr.py` in the
  project root (`/mnt/e/3ddogs`).

Example:

    cd /mnt/e/3ddogs/UnitreeGo2/urdf
    python visualize_go2_smr.py --smr ../../optical_sync_align_d29_t1_a_ready_go2_smr.npz
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import numpy as np
import pinocchio as pin
from pinocchio.visualize import MeshcatVisualizer

# Make project root importable so we can import `retargeting`.
THIS_FILE = Path(__file__).resolve()
PROJECT_ROOT = THIS_FILE.parents[2]  # /mnt/e/3ddogs
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from retargeting import Go2Kinematics  # type: ignore  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser(description="Visualize saved Go2 SMR trajectory with Meshcat")
    parser.add_argument(
        "--smr",
        type=str,
        required=True,
        help="Path to .npz file produced by generate_go2_smr.py (relative to this directory).",
    )
    args = parser.parse_args()

    smr_path = (THIS_FILE.parent / args.smr).resolve()
    if not smr_path.is_file():
        raise FileNotFoundError(smr_path)

    data = np.load(smr_path)
    q_bar = data["q_bar"]
    dt = float(data.get("dt", 1.0 / 60.0))

    # Build kinematic model from the local URDF.
    urdf_path = THIS_FILE.parent / "go2_description.urdf"
    go2 = Go2Kinematics.from_urdf(urdf_path)
    model = go2.model

    # Build visual geometry model.
    # The URDF uses relative mesh paths like "../dae/base.dae" with respect to
    # this `urdf` folder. We pass `package_dirs=[urdf_path.parent]` so
    # Pinocchio resolves them as `urdf_path.parent / filename`.
    example_mesh = (urdf_path.parent / "../dae/base.dae").resolve()
    print(f"Example mesh path that should exist: {example_mesh}")

    geom_model = pin.buildGeomFromUrdf(
        model,
        str(urdf_path),
        pin.GeometryType.VISUAL,
        None,
        [str(urdf_path.parent)],
    )

    # MeshcatVisualizer API is MeshcatVisualizer(model, collision_model=None, visual_model=None)
    # so we pass our geometry model as the visual model.
    viz = MeshcatVisualizer(model, None, geom_model)
    viz.initViewer(open=True)
    viz.loadViewerModel(rootNodeName="go2")

    # Align robot frame (URDF: +X forward, +Z up) to mocap world (Meshcat: +Y up,
    # motion facing roughly -X). This is purely for visualization.
    R = np.array(
        [
            [-1.0, 0.0, 0.0],  # e_x^r -> -X_w
            [0.0, 0.0, 1.0],   # e_y^r ->  Z_w
            [0.0, 1.0, 0.0],   # e_z^r ->  Y_w
        ]
    )
    T_align = np.eye(4)
    T_align[:3, :3] = R
    viz.viewer["go2"].set_transform(T_align)

    viz.display(q_bar[0])
    print(f"Loaded SMR: {smr_path}")
    print(f"Meshcat URL: {viz.viewer.url()}")

    # Playback loop
    try:
        while True:
            for q in q_bar:
                viz.display(q)
                time.sleep(dt)
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()

